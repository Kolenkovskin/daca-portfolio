-- ЗАПРОС 1 (R49): лучшие месяцы по обороту
SELECT
    DATE_TRUNC('month', kuupaev)::date AS kuu,
    COUNT(*) AS myyke,
    ROUND(SUM(total_price), 2) AS kaive,
    ROUND(AVG(total_price), 2) AS keskmine_ost
FROM sales_v_puhas
WHERE kuupaev <= DATE '2025-02-28'
GROUP BY kuu
ORDER BY kaive DESC
LIMIT 5;
-- РЕЗУЛЬТАТ (26 месяцев всего):
-- 2024-12  578  180 945.28  313.05
-- 2024-06  531  151 784.97  285.85
-- 2024-08  540  150 869.49  279.39
-- 2024-07  530  149 944.71  282.91
-- 2023-12  483  134 151.41  277.75
-- Декабрь и лето — сильнейшие месяцы; в декабре выше и средний чек.


-- ЗАПРОС 2 (R50, R57): рост к тому же месяцу прошлого года
WITH k AS (
    SELECT DATE_TRUNC('month', kuupaev)::date AS kuu,
           SUM(total_price) AS kaive
    FROM sales_v_puhas
    WHERE kuupaev <= DATE '2025-02-28'
    GROUP BY kuu
)
SELECT
    kuu,
    ROUND(kaive, 2) AS kaive,
    ROUND(100.0 * (kaive - LAG(kaive, 12) OVER (ORDER BY kuu))
          / LAG(kaive, 12) OVER (ORDER BY kuu), 2) AS kasv
FROM k
ORDER BY kuu DESC;
-- РЕЗУЛЬТАТ: все 14 месяцев, у которых есть прошлый год, выросли.
-- 2025-02  96 773.22   +2.68   ← слабее всех
-- 2025-01 102 133.87  +19.02
-- 2024-12 180 945.28  +34.88   ← сильнее всех
-- 2024-10 131 065.01  +33.89
-- 2024-01  85 812.10   +1.77
-- У 2023 года kasv = NULL: строки 12 месяцев назад нет, сравнивать не с чем.


-- ЗАПРОС 3: год к году (только полные годы 2023 и 2024)
WITH a AS (
    SELECT EXTRACT(YEAR FROM kuupaev)::int AS aasta,
           SUM(total_price) AS kaive
    FROM sales_v_puhas
    WHERE kuupaev BETWEEN DATE '2023-01-01' AND DATE '2024-12-31'
    GROUP BY aasta
)
SELECT
    aasta,
    ROUND(kaive, 2) AS kaive,
    ROUND(100.0 * (kaive - LAG(kaive) OVER (ORDER BY aasta))
          / LAG(kaive) OVER (ORDER BY aasta), 2) AS kasv
FROM a
ORDER BY aasta;
-- РЕЗУЛЬТАТ: 2023 — 1 286 616.68 €, 2024 — 1 519 821.23 €, рост +18.13%.
-- На данных с копиями было +16.50%: суммы завышены на ~45%,
-- а процент роста почти не изменился.


