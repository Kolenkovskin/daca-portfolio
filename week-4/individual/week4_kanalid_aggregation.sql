-- Задача Anna: какой канал растёт быстрее и за счёт чего —
-- больше покупок или дороже покупка?
-- Источник: вид sales_v_puhas, полные годы 2023 и 2024.
-- ============================================================


-- ЗАПРОС 1 (R56): каналы по годам
SELECT
    channel,
    EXTRACT(YEAR FROM kuupaev)::int AS aasta,
    COUNT(*) AS oste,
    ROUND(SUM(total_price), 2) AS kaive,
    ROUND(AVG(total_price), 2) AS keskmine_ost
FROM sales_v_puhas
WHERE kuupaev BETWEEN DATE '2023-01-01' AND DATE '2024-12-31'
GROUP BY channel, aasta
ORDER BY channel, aasta;
